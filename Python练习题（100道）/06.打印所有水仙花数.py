#编写一个程序，该程序用于找出并打印所有水仙花数

#水仙花数：一个三位数，其各个位的数的立方和等于该数本身

for num in range(100,1000):
    #获取百位数字

    i = num // 100

    #获取十位数字

    j = num // 10 % 10

    #获取个位数字

    k = num % 10

    sum_of_cubes = i ** 3 + j ** 3 + k ** 3

    #判断立方和是否等于该数本身

    if sum_of_cubes == num:
        print('水仙花数：',num)
