#案例尝试1

#目标：邮箱格式验证
#要求：用户的输入至少包含一个@和.两个符号，如果输入正确则输出：邮箱格式正确，输出错误则输出：邮箱格式错误

#思路一
#1.接收用户输入的邮箱
mail = input('请输入邮箱：')

#2.判断格式
if mail.count('@') == 1 and mail.count('.') >= 1:
    print('邮箱格式正确！')
else:
    print('邮箱格式错误！')

#思路二
#1.接收用户输入的邮箱
mail = input('请输入邮箱：')

#2.判断格式
if mail.count('@') == 1 and '.' in mail:
    print('邮箱格式正确！')
else:
    print('邮箱格式错误！')

